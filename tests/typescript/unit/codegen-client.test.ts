/**
 * `aster-gen client`: typed TypeScript clients from contract manifests.
 * The generator was ported from the Python CLI; its output was checked
 * byte-for-byte against that implementation when ported.
 */
import { describe, expect, it } from 'vitest';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { generateTypescriptClients, formatUsageSnippet } from '../../../bindings/typescript/packages/aster/src/codegen/client.js';

const manifest = {
  service: 'MissionControl',
  version: 1,
  contract_id: 'abc123',
  scoped: 'shared',
  methods: [
    {
      name: 'getStatus',
      pattern: 'unary',
      request_type: 'StatusRequest',
      response_type: 'StatusReply',
      request_wire_tag: 'mc/StatusRequest',
      response_wire_tag: 'mc/StatusReply',
      fields: [
        { name: 'agent_id', kind: 'string', nullable: false, default_kind: 'value', default_value: 'é' },
        { name: 'tags', kind: 'list', item_kind: 'string', default_kind: 'empty_list' },
      ],
      response_fields: [
        { name: 'status', kind: 'string' },
        { name: 'uptime', kind: 'int64', nullable: true, default_kind: 'none' },
      ],
    },
    { name: 'watch', pattern: 'bidi_stream', request_type: 'StatusRequest', response_type: 'StatusReply' },
  ],
};

describe('generateTypescriptClients', () => {
  it('writes types, a service client and a barrel', () => {
    const out = fs.mkdtempSync(path.join(os.tmpdir(), 'aster-codegen-'));
    try {
      const files = generateTypescriptClients([manifest], {
        outDir: out,
        namespace: 'AcmeOps',
        source: 'm.json',
        generatedAt: '2026-01-01T00:00:00Z',
      }).map((f) => path.relative(out, f));
      expect(files).toEqual([
        'acme_ops/types/mission-control-v1.ts',
        'acme_ops/services/mission-control-v1.ts',
        'acme_ops/index.ts',
      ]);
      const types = fs.readFileSync(path.join(out, files[0]), 'utf8');
      expect(types).toContain('agent_id: string = "\\u00e9";');
      expect(types).toContain('tags: string[] = [];');
      expect(types).toContain('uptime: number | null = null;');
      const client = fs.readFileSync(path.join(out, files[1]), 'utf8');
      expect(client).toContain('import { AsterClientWrapper, type AsterTransport, type BidiChannel, type CallOptions } from "@aster-rpc/aster";');
      expect(client).toContain('import { StatusReply, StatusRequest } from "../types/mission-control-v1.js";');
      expect(client).toContain('async getStatus(request: StatusRequest, callOptions?: CallOptions): Promise<StatusReply> {');
      expect(client).toContain('watch(callOptions?: CallOptions): BidiChannel {');
      expect(client).toContain(' * Auto-generated by: aster contract client m.json --lang typescript');
    } finally {
      fs.rmSync(out, { recursive: true, force: true });
    }
  });

  it('formats a usage snippet', () => {
    const s = formatUsageSnippet('gen', 'AcmeOps', [manifest], 'aster1xyz');
    expect(s).toContain('import { MissionControlClient } from "./acme_ops/services/mission-control-v1.js";');
    expect(s).toContain('const result = await svc.getStatus(new StatusRequest({}));');
  });
});
