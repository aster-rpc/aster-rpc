/// The Aster RPC ALPN (`b"aster/1"`). A node must be started with this ALPN
/// registered (e.g. `Node::start_with_alpns(cfg, vec![RPC_ALPN.to_vec()])`) for
/// [`Server`] to accept RPC connections.
pub use reactor::RPC_ALPN;

/// A registered service handler. Hand-written today; generated by
/// `#[aster::service]` in a later step. The instance is shared across all calls
/// (SHARED scope); session-scoped services land later.
#[async_trait::async_trait]
pub trait ServiceDispatch: Send + Sync + 'static {
    /// The service name (matched against `StreamHeader.service`).
    fn name(&self) -> &str;
    /// The service version (matched against `StreamHeader.version`).
    fn version(&self) -> i32;
    /// The method names this service implements. When non-empty, the server
    /// rejects any other method with `UNIMPLEMENTED` **before** [`dispatch`] is
    /// called, so a dispatcher need not handle unknown methods itself. An empty
    /// slice (the default) opts out — then the dispatcher owns method routing,
    /// including returning `UNIMPLEMENTED` for unknown methods. The
    /// `#[aster::service]` macro populates this.
    ///
    /// [`dispatch`]: ServiceDispatch::dispatch
    fn methods(&self) -> &[&str] {
        &[]
    }
    /// A capability requirement enforced on **every** method of this service
    /// (Gate 3), checked before dispatch against the caller's attributes. `None`
    /// (default) = no service-wide requirement.
    fn service_requires(&self) -> Option<CapabilityRequirement> {
        None
    }
    /// A capability requirement for a specific `method` (Gate 3), checked before
    /// dispatch in addition to [`service_requires`](ServiceDispatch::service_requires).
    /// `None` (default) = no method-level requirement. The `#[aster::service]`
    /// macro populates this from `#[rpc(requires = ...)]`.
    fn method_requires(&self, _method: &str) -> Option<CapabilityRequirement> {
        None
    }
    /// Maximum **body** frame size for `method`, in bytes. `None` (default)
    /// keeps the global `MAX_FRAME_SIZE`, so existing services are unaffected.
    ///
    /// This is a declaration, not an enforcement point: the transport applies
    /// it before reading a body frame, because by the time dispatch runs the
    /// allocation has already happened. Call headers are separately bounded by
    /// `MAX_CALL_HEADER_SIZE` for every service.
    fn max_frame_size(&self, _method: &str) -> Option<u32> {
        None
    }
    /// Refuse calls whose peer identity was not authenticated by the iroh
    /// handshake (§3.3).
    ///
    /// Default `false`, so no existing service changes behaviour. Coordination
    /// services set it: a voter's identity *is* its authority, so admitting the
    /// same apparent NodeId over an HTTP or WebTransport front end — where the
    /// peer id may be a client-supplied header — would let anyone impersonate a
    /// voter. Enforced by dispatch before the handler runs, so a service cannot
    /// forget the check.
    fn iroh_only(&self) -> bool {
        false
    }
    /// A default server-side timeout for `method`. `None` (default) = no
    /// method default. The handler's effective deadline is the minimum of the
    /// caller's `StreamHeader.deadline`, this, and the server's
    /// [`handler_timeout`](Server::handler_timeout); when it passes, the
    /// handler is cancelled (its future dropped) and the caller receives
    /// `DEADLINE_EXCEEDED`.
    fn method_timeout(&self, _method: &str) -> Option<Duration> {
        None
    }
    /// The cross-binding contract this service commits to, with the payload
    /// `TypeDef`s it references, for manifest publication. `None` (default)
    /// means the service has no publishable contract: a hand-written
    /// dispatcher. `#[aster::service]` populates it. An
    /// [`RpcSurface`](super::RpcSurface) under
    /// [`ManifestPublication::Strict`](super::ManifestPublication::Strict)
    /// refuses to activate a service that returns `None`.
    fn contract_artifacts(&self) -> Option<super::contract::ContractArtifacts> {
        None
    }
    /// Handle one call. `method` is `StreamHeader.method` (guaranteed to be in
    /// [`methods`](ServiceDispatch::methods) when that table is non-empty). The
    /// handler MUST terminate the call by consuming `call` via [`Call::respond`]
    /// or [`Call::finish`]; dropping it without a trailer aborts the stream and
    /// the client observes an error.
    async fn dispatch(&self, method: &str, call: Call);
}

type Registry = HashMap<ServiceKey, Arc<dyn ServiceDispatch>>;

type SessionFactories = HashMap<ServiceKey, SessionFactory>;

/// Services installed on a running server after its acceptor started: the
/// late-activated RPC surface of an [`AsterServer`](super::AsterServer). The
/// set is immutable once installed; withdrawing it replaces the whole set.
pub(crate) struct LateServices {
    pub(crate) services: Registry,
    /// Metadata-only probes of the session-scoped services below.
    pub(crate) session_probes: Registry,
    pub(crate) session_factories: SessionFactories,
}

/// The slot a deferred server's dispatchers consult after their own
/// registry. Generalises coordination's "live but late-bound" endpoints from
/// one service to a whole service set: the slot is wired into the dispatcher
/// before the acceptor starts, and until something is installed every call
/// that no host service claims answers `UNAVAILABLE` -- for every name alike,
/// so the refusal discloses nothing about what will be served.
#[derive(Default)]
pub(crate) struct LateSlot {
    current: std::sync::RwLock<Option<Arc<LateServices>>>,
}

impl LateSlot {
    pub(crate) fn get(&self) -> Option<Arc<LateServices>> {
        self.current.read().unwrap().clone()
    }

    /// Install `services`; calls routed after this returns reach them.
    pub(crate) fn install(&self, services: Arc<LateServices>) {
        *self.current.write().unwrap() = Some(services);
    }

    /// Withdraw the installed set; calls routed after this returns answer
    /// `UNAVAILABLE`. Calls already routed run to completion.
    pub(crate) fn clear(&self) -> Option<Arc<LateServices>> {
        self.current.write().unwrap().take()
    }
}

/// What a deferred server answers for a service no host service claims while
/// no surface is active. `UNAVAILABLE` is the status clients (and the default
/// [`RetryPolicy`](super::RetryPolicy)) treat as transient.
pub(crate) fn surface_inactive() -> RpcStatus {
    RpcStatus::error(StatusCode::Unavailable, "rpc surface not active")
}

/// Handler for an inbound connection on a non-`aster/1` ALPN. Invoked once per
/// accepted connection from the reactor's single accept loop, so it **must not
/// block** — hand the connection to a task or channel and return (e.g.
/// [`Expose::handle`](crate::expose::Expose::handle) feeds it to a reactor and
/// returns immediately; a custom protocol should `tokio::spawn` its own loop).
pub type AlpnHandler = Arc<dyn Fn(Connection) + Send + Sync>;

/// ALPN → handler routing table for the non-RPC fan-out.
type AlpnRoutes = HashMap<Vec<u8>, AlpnHandler>;

/// An RPC server bound to a node. Register services, then [`serve`](Server::serve).
pub struct Server {
    core: CoreNode,
    services: Registry,
    session_factories: SessionFactories,
    /// Metadata-only instances of session-scoped services (name, version,
    /// methods, frame caps). Never dispatched to.
    session_probes: Registry,
    attributes: AttributeStore,
    authenticator: Option<Arc<dyn Authenticator>>,
    routes: AlpnRoutes,
    max_sessions_per_connection: usize,
    handler_timeout: Option<Duration>,
    /// One timer facility per server, shared by every dispatcher it hands out.
    deadlines: DeadlineQueue,
    /// Foreign (binding-implemented) services, in registration order.
    foreign_specs: Vec<DynamicService>,
    dispatch_sink: Option<Arc<dyn DispatchSink>>,
    /// Built from the two fields above on first use and shared by every
    /// dispatcher, so all transports see one call table.
    foreign: OnceLock<Arc<Foreign>>,
    /// Telemetry sinks shared by every dispatcher (attribute extractors).
    telemetry: Telemetry,
    /// Late-bound services (deferred `AsterServer`); `None` = none expected.
    late: Option<Arc<LateSlot>>,
}

/// The default cap on how long any handler may run: Python's
/// `MAX_HANDLER_TIMEOUT_S`. See [`Server::handler_timeout`].
pub const DEFAULT_HANDLER_TIMEOUT: Duration = Duration::from_secs(300);

impl Server {
    /// Create a server over `node`. The node must have been started with the
    /// [`RPC_ALPN`] registered.
    pub fn new(node: &Node) -> Self {
        Self {
            core: node.core(),
            services: HashMap::new(),
            session_factories: HashMap::new(),
            session_probes: HashMap::new(),
            attributes: AttributeStore::new(),
            authenticator: None,
            routes: HashMap::new(),
            max_sessions_per_connection: DEFAULT_MAX_SESSIONS_PER_CONNECTION,
            handler_timeout: Some(DEFAULT_HANDLER_TIMEOUT),
            deadlines: DeadlineQueue::default(),
            foreign_specs: Vec::new(),
            dispatch_sink: None,
            foreign: OnceLock::new(),
            telemetry: Telemetry::default(),
            late: None,
        }
    }

    /// Consult `slot` for any service this server's own registry does not
    /// serve. Until a set is installed there, such calls answer
    /// `UNAVAILABLE` instead of `NOT_FOUND`. Used by a deferred
    /// [`AsterServer`](super::AsterServer).
    pub(crate) fn late_slot(mut self, slot: Arc<LateSlot>) -> Self {
        self.late = Some(slot);
        self
    }

    /// Where foreign calls and lifecycle events go (binding support). Set
    /// this before [`dispatcher`](Server::dispatcher) or
    /// [`serve`](Server::serve). With a sink, connection closes
    /// ([`DispatchEvent::ConnectionClosed`]) and connections on non-RPC
    /// ALPNs that no [`route_alpn`](Server::route_alpn) handler claims
    /// ([`DispatchEvent::NonRpc`]) are delivered too.
    #[cfg(feature = "binding-support")]
    pub fn dispatch_sink(mut self, sink: Arc<dyn DispatchSink>) -> Self {
        self.dispatch_sink = Some(sink);
        self.foreign = OnceLock::new();
        self
    }

    /// Serve a foreign (binding-implemented) service: calls that pass the
    /// gates are delivered to the [`dispatch_sink`](Server::dispatch_sink)
    /// with `service_idx` = the number of foreign services registered before
    /// this one. Validates `svc`, and refuses a `(name, version)` that is
    /// already registered, so register native services first.
    #[cfg(feature = "binding-support")]
    pub fn dynamic_service(mut self, svc: DynamicService) -> Result<Self> {
        svc.validate()?;
        let key = svc.key();
        if self.services.contains_key(&key)
            || self.session_factories.contains_key(&key)
            || self.foreign_specs.iter().any(|s| s.key() == key)
        {
            return Err(Error::InvalidArgument(format!(
                "service '{}' v{} is already registered",
                key.0, key.1
            )));
        }
        self.foreign_specs.push(svc);
        self.foreign = OnceLock::new();
        Ok(self)
    }

    /// The table through which the binding answers foreign calls. Every
    /// dispatcher of this server shares it.
    #[cfg(feature = "binding-support")]
    pub fn call_table(&self) -> super::foreign::CallTable {
        self.foreign().table.clone()
    }

    fn foreign(&self) -> Arc<Foreign> {
        self.foreign
            .get_or_init(|| {
                Arc::new(Foreign::new(
                    self.foreign_specs.clone(),
                    self.dispatch_sink.clone(),
                ))
            })
            .clone()
    }

    /// The longest any handler may run, whatever the caller asked for
    /// (default [`DEFAULT_HANDLER_TIMEOUT`], 300 s, matching the Python
    /// server). A call's effective deadline is the minimum of this, the
    /// caller's relative `StreamHeader.deadline` (measured from receipt), and
    /// the method's [`method_timeout`](ServiceDispatch::method_timeout). When
    /// it passes, the handler's future is dropped, [`Call::is_cancelled`]
    /// turns true, and the caller gets a `DEADLINE_EXCEEDED` trailer.
    ///
    /// `None` removes the cap, so only caller and method deadlines apply. Use
    /// that for services with legitimately unbounded streams.
    pub fn handler_timeout(mut self, max: Option<Duration>) -> Self {
        self.handler_timeout = max;
        self
    }

    /// Cap the number of **active** sessions one connection may hold
    /// (Aster-multiplexed-streams §7.5; default 1024). A call that would open
    /// one more is refused with `RESOURCE_EXHAUSTED`. Applies to
    /// connection-scoped (Iroh) sessions; HTTP-scoped sessions are not capped.
    pub fn max_sessions_per_connection(mut self, max: usize) -> Self {
        self.max_sessions_per_connection = max;
        self
    }

    /// Attach a pre-dispatch [`Authenticator`] (builder-style). It runs on every
    /// call before the Gate-3 capability check, can reject, and can resolve a
    /// principal + attributes (merged under the [`AttributeStore`]; it never adds
    /// a role to a peer with a live enrollment session). This is where HTTP Bearer/JWT or any custom auth
    /// lives — it applies to whichever transport drives the dispatcher.
    pub fn authenticator(mut self, auth: impl Authenticator) -> Self {
        self.authenticator = Some(Arc::new(auth));
        self
    }

    /// Add a Rust-native attribute extractor (design §4.4): for every call
    /// that passes the gates, `f` may return a value for the OTel attribute
    /// `key` on the call's `rpc` span (e.g. a tenant derived from several
    /// attributes). Declarative extractors (`attr:` / `meta:` / `baggage:`)
    /// are configured on the pipeline instead
    /// (`ObservabilityConfig::attribute_extractors`). Runs only while an OTel
    /// tracer provider is installed. Set before
    /// [`dispatcher`](Server::dispatcher) or [`serve`](Server::serve).
    #[cfg(feature = "otel")]
    pub fn attribute_extractor(
        mut self,
        key: impl Into<String>,
        f: impl Fn(&super::ExtractContext<'_>) -> Option<String> + Send + Sync + 'static,
    ) -> Self {
        self.telemetry.extractors.push(key.into(), Arc::new(f));
        self
    }

    /// Set an already-boxed authenticator (used by [`AsterServer`](crate::rpc::AsterServer)).
    pub(crate) fn authenticator_arc(mut self, auth: Arc<dyn Authenticator>) -> Self {
        self.authenticator = Some(auth);
        self
    }

    /// Register a service dispatcher (builder-style; chainable).
    pub fn register(mut self, svc: impl ServiceDispatch) -> Self {
        self.services
            .insert((svc.name().to_string(), svc.version()), Arc::new(svc));
        self
    }

    /// Register an already-boxed dispatcher. Used by [`AsterServer`](crate::rpc::AsterServer)
    /// to collect heterogeneous services into one registry.
    pub(crate) fn register_arc(mut self, svc: Arc<dyn ServiceDispatch>) -> Self {
        self.services
            .insert((svc.name().to_string(), svc.version()), svc);
        self
    }

    /// Register a **session-scoped** service: `factory` builds a fresh instance
    /// per session. State on the instance is private to that session — the
    /// analogue of Python's `scoped="session"` services.
    ///
    /// Over Iroh a session is identified by `(connection, StreamHeader.session_id)`
    /// and follows Aster-multiplexed-streams §7.5 exactly as Python and Java do:
    ///
    /// - a call with `session_id == 0` is refused with `FAILED_PRECONDITION`;
    /// - a new id above the connection's highest opened id creates an instance,
    ///   unless the connection already holds
    ///   [`max_sessions_per_connection`](Server::max_sessions_per_connection)
    ///   active sessions (`RESOURCE_EXHAUSTED`);
    /// - an id at or below that high-water mark that is not active is
    ///   `NOT_FOUND`;
    /// - every session on a connection is dropped when the connection closes.
    ///
    /// Another connection presenting the same id gets its own instance, never
    /// this one. Over HTTP-style transports, which have no connection id, the
    /// `aster-session-id` header (or a non-zero `session_id`) names the
    /// session, scoped to the caller's principal (the [`Authenticator`]
    /// principal, else the transport's peer id); those instances have no cap
    /// and live until [`end_session`]. Explicit public transport dispatchers reject
    /// session-scoped services before creating an instance.
    ///
    /// [`end_session`]: Dispatcher::end_session
    pub fn register_session<S, F>(mut self, factory: F) -> Self
    where
        S: ServiceDispatch,
        F: Fn() -> S + Send + Sync + 'static,
    {
        // One instance read for its constant metadata: name, version, and --
        // since the frame-limit resolver runs before any session exists -- the
        // declared per-method frame caps. Keeping it means session-scoped
        // services get their limits installed like any other; without it they
        // silently kept the 16 MiB default.
        let probe: Arc<dyn ServiceDispatch> = Arc::new(factory());
        let factory: SessionFactory =
            Arc::new(move || Ok(SessionInstance::Native(Arc::new(factory()))));
        let key = (probe.name().to_string(), probe.version());
        self.session_probes.insert(key.clone(), probe);
        self.session_factories.insert(key, factory);
        self
    }

    /// Use a shared [`AttributeStore`] for Gate-3 capability checks. Keep a clone
    /// of the same store and populate it from your admission logic (e.g. after
    /// verifying a peer's enrollment credential) so per-call `requires` checks see
    /// the peer's roles. Without this, the server uses an empty store (only
    /// no-requirement methods are reachable).
    pub fn attributes(mut self, store: AttributeStore) -> Self {
        self.attributes = store;
        self
    }

    /// Route inbound connections on a non-`aster/1` `alpn` to `handler`,
    /// instead of dropping them. This is the fan-out that lets one node serve
    /// RPC **and** other protocols on a single accept loop: the reactor owns
    /// `accept()`, sends `aster/1` to the RPC pipeline, and hands every other
    /// ALPN to its registered handler (so a second acceptor — which would split
    /// connections arbitrarily — is never needed).
    ///
    /// The node must also be started with `alpn` registered
    /// ([`start_with_alpns`](crate::Node::start_with_alpns), or
    /// [`AsterServerBuilder::route_alpn`](crate::rpc::AsterServerBuilder::route_alpn)
    /// which registers it for you). `handler` must not block — see
    /// [`AlpnHandler`].
    pub fn route_alpn(
        mut self,
        alpn: impl Into<Vec<u8>>,
        handler: impl Fn(Connection) + Send + Sync + 'static,
    ) -> Self {
        self.routes.insert(alpn.into(), Arc::new(handler));
        self
    }

    /// Register an already-boxed ALPN handler. Used by
    /// [`AsterServer`](crate::rpc::AsterServer) to forward its collected routes.
    pub(crate) fn route_alpn_arc(mut self, alpn: Vec<u8>, handler: AlpnHandler) -> Self {
        self.routes.insert(alpn, handler);
        self
    }

    /// Route inbound connections on `alpn` to an [`Expose`](crate::expose::Expose)
    /// registry: each is attached + fed so its relay streams reach the exposed
    /// services. The convenience over [`route_alpn`](Self::route_alpn) for the
    /// common "RPC + expose on one node" case.
    #[cfg(feature = "expose")]
    pub fn expose_alpn(self, alpn: impl Into<Vec<u8>>, expose: crate::expose::Expose) -> Self {
        self.route_alpn(alpn, move |conn| expose.handle(&conn))
    }

    /// Snapshot the registered services + the Gate-3 attribute store as a
    /// shareable, transport-agnostic [`Dispatcher`]. Each transport (the Iroh
    /// reactor loop, an HTTP listener, …) holds a clone and feeds it
    /// [`IncomingCall`]s. Grab this **before** [`serve`](Server::serve) when you
    /// want to serve the same services over more than one transport:
    ///
    /// ```ignore
    /// let server = Server::new(&node).register(svc).attributes(attrs);
    /// let dispatcher = server.dispatcher(); // hand to a second transport (HTTP)
    /// let handle = server.serve();          // Iroh accept loop
    /// ```
    pub fn dispatcher(&self) -> Dispatcher {
        Dispatcher {
            services: Arc::new(self.services.clone()),
            session_probes: Arc::new(self.session_probes.clone()),
            session_factories: Arc::new(self.session_factories.clone()),
            sessions: Arc::new(SessionStore::new(self.max_sessions_per_connection)),
            attributes: self.attributes.clone(),
            authenticator: self.authenticator.clone(),
            public_transport: false,
            handler_timeout: self.handler_timeout,
            deadlines: self.deadlines.clone(),
            foreign: self.foreign(),
            telemetry: self.telemetry.clone(),
            late: self.late.clone(),
        }
    }

    /// Spawn the Iroh reactor accept+dispatch loop. The returned [`ServerHandle`]
    /// keeps the loop alive; dropping it detaches (the loop runs until the node
    /// closes), `abort()` stops it. For a multi-transport process, call
    /// [`dispatcher`](Server::dispatcher) first, then `serve`.
    pub fn serve(self) -> ServerHandle {
        let dispatcher = self.dispatcher();
        let resolver = dispatcher.frame_limit_resolver();
        let foreign = dispatcher.foreign.clone();
        let handle = reactor::start_reactor_with_limits(self.core, 256, Some(resolver));
        let (mut event_rx, mut non_rpc_rx) = handle.into_parts();

        // RPC pipeline: dispatch each `aster/1` call.
        let rpc_join = tokio::spawn(async move {
            tracing::debug!(target: SERVER, "rpc serve loop started");
            // Connections seen so far, for the connection counters (health,
            // OTel). The reactor reports closes only, so a connection counts
            // as open from its first call. Only kept when something counts
            // them; this loop is its only user, so it needs no lock.
            let track_connections = dispatcher.telemetry.tracks_connections();
            let mut open_connections: HashMap<u64, ConnObs> = HashMap::new();
            while let Some(ev) = event_rx.recv().await {
                match ev {
                    ReactorEvent::Call(call) => {
                        let obs = dispatcher.telemetry.start_call();
                        if track_connections && !open_connections.contains_key(&call.connection_id)
                        {
                            open_connections.insert(
                                call.connection_id,
                                dispatcher.telemetry.connection_opened(),
                            );
                        }
                        // Route inline: decoding, lookup, session resolution
                        // and Gate 3 are synchronous, so a refused call costs
                        // no task. Only calls that reach a handler (or an
                        // authenticator) are spawned. Routing here also orders
                        // every session lookup before the connection's
                        // `ConnectionClosed`, which this same loop handles.
                        let parts = CallParts::from_incoming(call);
                        match dispatcher.route(&parts) {
                            Route::Reject(status) => {
                                finish_refused(obs, &parts, &status);
                                reject_now(parts.response_sender, &status);
                            }
                            // Foreign fast path: delivered from this loop,
                            // no task per call.
                            Route::Dispatch(routed) if routed.is_foreign() => {
                                dispatcher.deliver_foreign(routed, parts, obs);
                            }
                            route => {
                                let dispatcher = dispatcher.clone();
                                tokio::spawn(async move {
                                    dispatcher.complete_observed(route, parts, obs).await
                                });
                            }
                        }
                    }
                    // §7.5: a connection's sessions die with it.
                    // Foreign sessions report `SessionClosed` as they are
                    // dropped here, ahead of the `ConnectionClosed` below.
                    ReactorEvent::ConnectionClosed {
                        connection_id,
                        peer_id,
                        ..
                    } => {
                        let reaped = dispatcher.close_connection(connection_id);
                        if let Some(conn) = open_connections.remove(&connection_id) {
                            dispatcher.telemetry.connection_closed(conn);
                        }
                        tracing::debug!(
                            target: SERVER,
                            connection_id,
                            peer = peer_id.as_str(),
                            sessions_reaped = reaped,
                            "connection closed"
                        );
                        if dispatcher.foreign.has_sink {
                            dispatcher
                                .foreign
                                .connection_closed(connection_id, Arc::from(peer_id));
                        }
                    }
                }
            }
            tracing::debug!(target: SERVER, "rpc serve loop ended");
        });

        // Non-RPC fan-out: route every other ALPN to its handler. Always
        // drained (even with no routes) so the accept loop never stalls on a
        // full non-rpc channel.
        let routes = Arc::new(self.routes);
        let route_join = tokio::spawn(async move {
            while let Some((alpn, core)) = non_rpc_rx.recv().await {
                match routes.get(&alpn) {
                    Some(handler) => handler(Connection::new(core)),
                    // Unclaimed, but a binding is listening: its handlers
                    // (e.g. frozen consumer admission) take it.
                    None if foreign.has_sink => {
                        if let Some(permit) = foreign.sink.try_admit(DispatchAdmission::NonRpc) {
                            match foreign.sink.deliver_admitted(
                                DispatchEvent::NonRpc {
                                    alpn,
                                    connection: core,
                                },
                                permit,
                            ) {
                                Ok(()) => {}
                                Err(DispatchSendError::Closed((event, permit))) => {
                                    drop(event);
                                    drop(permit);
                                }
                                Err(DispatchSendError::Full((event, permit))) => {
                                    tracing::error!(target: SERVER, "admitted non-RPC dispatch event quota exhausted");
                                    drop(event);
                                    drop(permit);
                                }
                            }
                        } else {
                            tracing::debug!(
                                target: SERVER,
                                alpn = %String::from_utf8_lossy(&alpn),
                                "foreign dispatch admission full; connection dropped"
                            );
                            drop(core);
                        }
                    }
                    // No handler for this ALPN: drop `core`, which closes the
                    // connection. The peer observes a closed connection.
                    None => {
                        tracing::debug!(
                            target: SERVER,
                            alpn = %String::from_utf8_lossy(&alpn),
                            "no handler for ALPN; connection dropped"
                        );
                        drop(core)
                    }
                }
            }
        });

        ServerHandle {
            rpc_join,
            route_join,
        }
    }
}

/// The transport-agnostic RPC dispatcher: the registered services plus the
/// Gate-3 [`AttributeStore`], shareable across transports. Produced by
/// [`Server::dispatcher`]. The Iroh reactor loop uses one internally; a second
/// transport (e.g. HTTP) holds a clone and calls
/// [`dispatch_call`](Dispatcher::dispatch_call) per decoded inbound call.
///
/// Cloning is cheap — the service registry is `Arc`-shared and the attribute
/// store is `Arc`-backed — so all clones see the same services and the same
/// (live, mutable) attributes.
#[derive(Clone)]
pub struct Dispatcher {
    services: Arc<Registry>,
    /// Metadata-only probes for session-scoped services; see
    /// [`frame_limit_resolver`](Dispatcher::frame_limit_resolver).
    session_probes: Arc<Registry>,
    session_factories: Arc<SessionFactories>,
    /// Live per-session instances, shared across clones of this dispatcher.
    sessions: Arc<SessionStore>,
    attributes: AttributeStore,
    authenticator: Option<Arc<dyn Authenticator>>,
    /// Anonymous transport policy: no address-derived authority or sessions.
    public_transport: bool,
    handler_timeout: Option<Duration>,
    deadlines: DeadlineQueue,
    /// Foreign services, the sink and the shared call table.
    foreign: Arc<Foreign>,
    telemetry: Telemetry,
    /// Late-bound services, shared by every clone (so an HTTP transport sees
    /// an activation too).
    late: Option<Arc<LateSlot>>,
}

impl Dispatcher {
    /// Clone this dispatcher with authentication specific to one listener.
    ///
    /// Services, attributes, sessions and the foreign call table remain shared.
    /// Other clones keep their existing authenticator, so an HTTP credential
    /// policy need not alter the Iroh listener's policy. Authenticating a
    /// principal does not change the transport's [`PeerProvenance`].
    pub fn with_authenticator(&self, auth: Arc<dyn Authenticator>) -> Self {
        Self {
            authenticator: Some(auth),
            public_transport: false,
            ..self.clone()
        }
    }

    /// Clone for an explicitly public, anonymous transport.
    ///
    /// The clone has no authenticator or enrolled caller attributes. Gate 3
    /// still applies with empty attributes and Iroh-only services still require
    /// transport proof. Session-scoped services are rejected before any session
    /// factory runs: an address or caller-supplied session id cannot safely
    /// isolate anonymous callers. Other dispatcher clones are unchanged.
    pub fn for_public_transport(&self) -> Self {
        Self {
            authenticator: None,
            attributes: AttributeStore::new(),
            public_transport: true,
            ..self.clone()
        }
    }

    /// Whether this dispatcher's own (host) registry serves `key`, natively,
    /// session-scoped or foreign. Late-bound services are not counted.
    pub(crate) fn serves_host(&self, key: &ServiceKey) -> bool {
        self.services.contains_key(key)
            || self.session_factories.contains_key(key)
            || self.foreign.service(key).is_some()
    }

    /// The session store shared by every clone of this dispatcher.
    pub(crate) fn session_store(&self) -> &SessionStore {
        &self.sessions
    }

    /// Build the transport's per-method frame-limit resolver from the
    /// registered services.
    ///
    /// The transport hands over raw header bytes and gets a decision back; it
    /// never learns the payload format. Decoding `StreamHeader` -- and knowing
    /// what a service or a method is -- stays here, on the `aster` side of the
    /// boundary.
    pub fn frame_limit_resolver(&self) -> reactor::FrameLimitResolver {
        let services = self.services.clone();
        // Session-scoped services are registered as factories, so the shared
        // registry does not contain them. Consulting only that registry left
        // every session-scoped service on the 16 MiB default.
        let probes = self.session_probes.clone();
        // Foreign services answer from their `MethodLimits`, shared and
        // session-scoped alike.
        let foreign = self.foreign.clone();
        // A late-activated surface's caps apply once it is installed.
        let late = self.late.clone();
        Arc::new(move |header: &[u8]| match decode_stream_header(header) {
            // Undecodable header: reject the stream rather than fall back to a
            // generous default and read a body behind it.
            Err(_) => reactor::FrameLimit::Reject,
            Ok(h) => {
                let key = (h.service.clone(), h.version);
                let cap = match services.get(&key).or_else(|| probes.get(&key)) {
                    Some(s) => s.max_frame_size(&h.method),
                    None => match foreign.service(&key) {
                        Some(s) => s.max_frame_size(&h.method),
                        None => late.as_ref().and_then(|slot| slot.get()).and_then(|l| {
                            l.services
                                .get(&key)
                                .or_else(|| l.session_probes.get(&key))
                                .and_then(|s| s.max_frame_size(&h.method))
                        }),
                    },
                };
                match cap {
                    None => reactor::FrameLimit::Default,
                    Some(n) => reactor::FrameLimit::Limit(n),
                }
            }
        })
    }

    /// Dispatch one already-decoded inbound [`IncomingCall`]: run the
    /// pre-dispatch gates (service / method / serialization mode / Gate-3
    /// capability) and, if they pass, hand a [`Call`] to the matched service.
    /// Any transport that can produce an `IncomingCall` (peer id, header +
    /// request payload, a response-frame channel) can drive RPC through this.
    pub async fn dispatch_call(&self, call: IncomingCall) {
        self.dispatch_parts(CallParts::from_incoming(call)).await;
    }

    /// Dispatch from connection-agnostic [`CallParts`] — the entry point for a
    /// non-Iroh transport (e.g. HTTP) that has no `CoreConnection`. Builds the
    /// parts itself (peer id, header + request payloads, a response-frame
    /// channel) and calls this. Same gating and handler invocation as
    /// [`dispatch_call`](Dispatcher::dispatch_call).
    ///
    /// Equivalent to [`route`](Dispatcher::route) followed by
    /// [`complete`](Dispatcher::complete); resolves when the handler returns.
    pub async fn dispatch_parts(&self, parts: CallParts) {
        let route = self.route(&parts);
        self.complete(route, parts).await;
    }

    /// Decide, synchronously, what happens to a call: decode the header, look
    /// up the service, check `iroh_only`, the method and the serialization
    /// mode, resolve the session (§7.5), then run Gate 3. Nothing here awaits
    /// and no handler runs; pass the result to [`complete`](Dispatcher::complete).
    ///
    /// Checks run in that order and the first failure wins (see
    /// `conformance/scenarios/error-mapping.yaml`). With an [`Authenticator`]
    /// configured, Gate 3 (and the lookup of an HTTP-scoped session, which is
    /// keyed by the authenticated principal) moves to `complete`, and the
    /// result is [`Route::Authenticate`].
    pub fn route(&self, parts: &CallParts) -> Route {
        let header = match decode_stream_header(&parts.header_payload) {
            Ok(h) => h,
            // Aster-SPEC §6.5 and the Python server: a header that does not
            // decode is the caller's error, not ours.
            Err(_) => {
                return Route::Reject(RpcStatus::error(
                    StatusCode::InvalidArgument,
                    "malformed stream header",
                ))
            }
        };
        if header.service.is_empty() {
            return Route::Reject(RpcStatus::error(
                StatusCode::InvalidArgument,
                "missing service name",
            ));
        }

        let key = (header.service.clone(), header.version);
        let (meta, factory, foreign) = if let Some(s) = self.services.get(&key) {
            (s.clone(), None, None)
        } else if let (Some(probe), Some(f)) = (
            self.session_probes.get(&key),
            self.session_factories.get(&key),
        ) {
            // Session-scoped: gate on the metadata probe; the instance is
            // resolved below, after the cheap checks.
            (probe.clone(), Some(f.clone()), None)
        } else if let Some(svc) = self.foreign.service(&key) {
            (
                svc.clone() as Arc<dyn ServiceDispatch>,
                self.foreign.factory(&key).cloned(),
                Some(svc.clone()),
            )
        } else {
            match self.late.as_ref().map(|slot| slot.get()) {
                // No late slot (every server but a deferred AsterServer).
                None => return Route::Reject(not_found(&header)),
                // Deferred and not active: fail closed, the same for every
                // name, before any service-specific check.
                Some(None) => return Route::Reject(surface_inactive()),
                Some(Some(late)) => {
                    if let Some(s) = late.services.get(&key) {
                        (s.clone(), None, None)
                    } else if let (Some(probe), Some(f)) = (
                        late.session_probes.get(&key),
                        late.session_factories.get(&key),
                    ) {
                        (probe.clone(), Some(f.clone()), None)
                    } else {
                        return Route::Reject(not_found(&header));
                    }
                }
            }
        };

        // Provenance BEFORE method routing and before any handler runs. A
        // service that declares `iroh_only` must never see a call whose peer id
        // the transport could not vouch for, and it must not have to remember
        // to check. `NotFound` rather than `PermissionDenied`: over an
        // unauthenticated transport the service's existence is itself not
        // something to confirm.
        if meta.iroh_only() && !parts.provenance.is_authenticated() {
            return Route::Reject(not_found(&header));
        }
        if self.public_transport && factory.is_some() {
            return Route::Reject(RpcStatus::error(
                StatusCode::Unauthenticated,
                "session-scoped service requires an authenticated principal",
            ));
        }

        let unimplemented = || {
            Route::Reject(RpcStatus::error(
                StatusCode::Unimplemented,
                format!(
                    "method '{}.{}' not implemented",
                    header.service, header.method
                ),
            ))
        };
        let method_idx = match &foreign {
            Some(svc) => match svc.method_index(&header.method) {
                Some(idx) => idx,
                None => return unimplemented(),
            },
            None => {
                let methods = meta.methods();
                if !methods.is_empty() && !methods.iter().any(|m| *m == header.method) {
                    return unimplemented();
                }
                0
            }
        };

        // Rust services speak XLANG on the wire only (JSON is intentionally
        // unsupported); a foreign service accepts the modes it declared.
        let mode_ok = match &foreign {
            Some(svc) => svc.accepts_wire_mode(header.serialization_mode),
            None => header.serialization_mode == SerializationMode::Xlang.as_i8(),
        };
        if !mode_ok {
            return Route::Reject(RpcStatus::error(
                StatusCode::InvalidArgument,
                format!(
                    "unsupported serialization mode: {}",
                    header.serialization_mode
                ),
            ));
        }

        // Reserve the call and its connection before a session factory can
        // mutate the session store. Overload is therefore pre-start: no
        // session id is cached and no foreign factory side effect occurs.
        let call_admission = if foreign.is_some() {
            let Some(permit) = self.foreign.sink.try_admit(DispatchAdmission::Call) else {
                return Route::Reject(RpcStatus::error(
                    StatusCode::ResourceExhausted,
                    "foreign dispatch admission limit reached",
                ));
            };
            if !self.foreign.ensure_connection_admitted(parts.connection_id) {
                return Route::Reject(RpcStatus::error(
                    StatusCode::ResourceExhausted,
                    "foreign dispatch admission limit reached",
                ));
            }
            Some(permit)
        } else {
            None
        };

        let target = match factory {
            // SHARED service: one instance for everyone, and no session id.
            None => match check_shared(&header.service, header.session_id) {
                Ok(()) => match &foreign {
                    Some(svc) => Target::Foreign {
                        svc: svc.clone(),
                        session: None,
                    },
                    None => Target::Ready(meta.clone()),
                },
                Err(e) => return Route::Reject(e.status()),
            },
            Some(factory) => match parts.connection_id {
                // §7.5: keyed by (connection, session id), never by the id
                // alone. Resolved here, before any authenticator, so that this
                // runs in the serve loop ahead of the connection's
                // `ConnectionClosed` and can never resurrect a reaped entry.
                Some(conn) if header.session_id != 0 => {
                    match self
                        .sessions
                        .resolve_connection(conn, &key, header.session_id, &factory)
                    {
                        Ok(inst) => target_of(inst, &foreign),
                        Err(e) => return Route::Reject(e.status()),
                    }
                }
                Some(_) => return Route::Reject(missing_session(&header.service).status()),
                // No connection (HTTP): string id, scoped to the caller's
                // principal, which an authenticator may still change.
                None => match http_session_id(&header) {
                    None => return Route::Reject(missing_session(&header.service).status()),
                    Some(sid) if self.authenticator.is_some() => {
                        Target::HttpSession { factory, sid }
                    }
                    Some(sid) => {
                        match self
                            .sessions
                            .resolve_http(&parts.peer_id, &key, &sid, &factory)
                        {
                            Ok(instance) => target_of(instance, &foreign),
                            Err(error) => return Route::Reject(error.status()),
                        }
                    }
                },
            },
        };

        // The deadline clock starts at receipt (the header carries relative
        // seconds; Aster-SPEC §6.8).
        let deadline = [
            self.handler_timeout,
            (header.deadline > 0).then(|| Duration::from_secs(header.deadline as u64)),
            meta.method_timeout(&header.method),
        ]
        .into_iter()
        .flatten()
        .min()
        .map(|t| Instant::now() + t);

        let routed = Routed {
            header,
            key,
            meta,
            foreign,
            method_idx,
            target,
            attributes: HashMap::new(),
            deadline,
            call_admission,
        };
        if self.authenticator.is_some() {
            return Route::Authenticate(routed);
        }
        let attributes = if self.public_transport {
            HashMap::new()
        } else {
            self.attributes.get(&parts.peer_id)
        };
        if let Err(status) = gate3(&*routed.meta, &routed.header, &attributes) {
            return Route::Reject(status);
        }
        Route::Dispatch(Routed {
            attributes,
            ..routed
        })
    }

    /// Finish a call routed by [`route`](Dispatcher::route): send the refusal
    /// trailer, or run the authenticator and Gate 3 if still pending, then
    /// inflate the first request frame and run the handler. Resolves when the
    /// handler returns.
    pub async fn complete(&self, route: Route, parts: CallParts) {
        let obs = self.telemetry.start_call();
        self.complete_observed(route, parts, obs).await;
    }

    /// [`complete`](Dispatcher::complete) for a call whose telemetry the
    /// caller already started.
    async fn complete_observed(&self, route: Route, mut parts: CallParts, mut obs: CallObs) {
        let routed = match route {
            Route::Reject(status) => {
                finish_refused(obs, &parts, &status);
                emit_rpc_status(&parts.response_sender, &status).await;
                return;
            }
            Route::Dispatch(mut routed) => {
                open_routed(&mut obs, &mut routed, &parts.peer_id);
                routed
            }
            Route::Authenticate(mut routed) => {
                open_routed(&mut obs, &mut routed, &parts.peer_id);
                match self.authenticate(routed, &mut parts).await {
                    Ok(Some(routed)) => routed,
                    Ok(None) => {
                        // The transport has already stopped listening. Drop
                        // authentication without emitting a terminal response.
                        finish_refused(
                            obs,
                            &parts,
                            &RpcStatus::error(StatusCode::Cancelled, "peer cancelled"),
                        );
                        return;
                    }
                    Err(status) => {
                        finish_refused(obs, &parts, &status);
                        emit_rpc_status(&parts.response_sender, &status).await;
                        return;
                    }
                }
            }
        };
        if routed.is_foreign() {
            self.deliver_foreign(routed, parts, obs);
            return;
        }
        let Routed {
            header,
            target,
            attributes,
            deadline,
            ..
        } = routed;
        obs.dispatching(&header, &parts.peer_id, &attributes);
        let svc = match target {
            Target::Ready(svc) => svc,
            Target::Foreign { .. } => unreachable!("foreign target delivered above"),
            // `authenticate` resolves every HTTP session before returning.
            Target::HttpSession { .. } => unreachable!("HTTP session left unresolved"),
        };

        // §5.6: inflate a compressed first request frame once, after the gates
        // (an unauthorised caller costs no decompression), so handlers see the
        // logical payload. Later client-stream / bidi frames are inflated as
        // they are read.
        if parts.request_flags & FLAG_COMPRESSED != 0 {
            match decompress(&parts.request_payload) {
                Ok(p) => {
                    parts.request_payload = p;
                    parts.request_flags &= !FLAG_COMPRESSED;
                }
                Err(e) => {
                    let status = corrupt_frame_status(&e);
                    warn_corrupt_frame(&header, &parts.peer_id, 0, &e);
                    finish_refused(obs, &parts, &status);
                    emit_rpc_status(&parts.response_sender, &status).await;
                    return;
                }
            }
        }

        // The call's `rpc` span (opened in routing) wraps the handler, so its
        // own events, and the client spans of calls it makes, carry the call's
        // identity. Disabled (the common case): no span.
        let span = obs.span().clone();
        let pass = obs.pass();
        let method = header.method.clone();
        // A peer cancel (or the stream failing under the call) drops the
        // handler, as a deadline does, whatever the pattern: a unary handler
        // has no send to fail, so it would otherwise run to completion.
        let peer_cancel = peer_cancelled(parts.cancel_notify.clone(), parts.cancelled.clone());
        let Some(at) = deadline else {
            let handler = super::observe::scoped(
                pass,
                svc.dispatch(&method, Call::new(parts, header, attributes, None, obs))
                    .instrument(span.clone()),
            );
            tokio::select! {
                biased;
                () = handler => {}
                () = peer_cancel => {
                    span.in_scope(|| {
                        tracing::debug!(target: DISPATCH, "peer cancelled; handler dropped")
                    });
                }
            }
            return;
        };
        let cancelled = parts.cancelled.clone();
        let sender = parts.response_sender.clone();
        let (fire, fired) = tokio::sync::oneshot::channel::<()>();
        let _guard = self.deadlines.register(at, move || {
            let _ = fire.send(());
        });
        let handler = svc.dispatch(&method, Call::new(parts, header, attributes, Some(at), obs));
        let deadline_span = span.clone();
        let handler = super::observe::scoped(pass, handler.instrument(span));
        tokio::select! {
            biased;
            () = handler => {}
            () = peer_cancel => {
                // No trailer: the peer is not listening for one (§6.0).
                deadline_span.in_scope(|| {
                    tracing::debug!(target: DISPATCH, "peer cancelled; handler dropped")
                });
            }
            _ = fired => {
                // The handler future is dropped when this arm wins, which
                // cancels it. Flag the call too, for anything it spawned.
                cancelled.store(true, Ordering::Release);
                deadline_span.in_scope(|| {
                    tracing::debug!(target: DISPATCH, "deadline exceeded; handler cancelled")
                });
                emit_trailer(&sender, StatusCode::DeadlineExceeded, "deadline exceeded").await;
            }
        }
    }

    /// The async half of routing when an [`Authenticator`] is configured: run
    /// it, merge its attributes under the store's (no role for an enrolled peer), apply its
    /// principal, run Gate 3, and resolve an HTTP-scoped session under the
    /// resulting principal.
    async fn authenticate(
        &self,
        mut routed: Routed,
        parts: &mut CallParts,
    ) -> std::result::Result<Option<Routed>, RpcStatus> {
        let (mut attrs, credentialed) = self.attributes.resolve(&parts.peer_id);
        if let Some(auth) = self.authenticator.as_ref() {
            // Authentication spends the same routed deadline as the handler.
            // Register before invoking the hook, so a stalled foreign auth
            // upcall is dropped on deadline or transport cancellation too.
            if parts.cancelled.load(Ordering::Acquire) {
                return Ok(None);
            }
            let deadline_status =
                || RpcStatus::error(StatusCode::DeadlineExceeded, "deadline exceeded");
            if routed.deadline.is_some_and(|at| Instant::now() >= at) {
                parts.cancelled.store(true, Ordering::Release);
                return Err(deadline_status());
            }
            let (fire, fired) = tokio::sync::oneshot::channel::<()>();
            let _guard = routed.deadline.map(|at| {
                self.deadlines.register(at, move || {
                    let _ = fire.send(());
                })
            });
            let ctx = AuthContext {
                peer_id: parts.peer_id.clone(),
                service: routed.header.service.clone(),
                method: routed.header.method.clone(),
                session_id: routed.header.session_id,
                metadata: metadata_map(&routed.header),
            };
            let outcome = tokio::select! {
                biased;
                () = peer_cancelled(parts.cancel_notify.clone(), parts.cancelled.clone()) => {
                    return Ok(None);
                }
                _ = fired, if routed.deadline.is_some() => {
                    parts.cancelled.store(true, Ordering::Release);
                    return Err(deadline_status());
                }
                outcome = auth.authenticate(&ctx) => outcome?,
            };
            // A ready hook can race the deadline task or a flag-only transport.
            // Do not resolve a session or dispatch after either has won.
            if parts.cancelled.load(Ordering::Acquire) {
                return Ok(None);
            }
            if routed.deadline.is_some_and(|at| Instant::now() >= at) {
                parts.cancelled.store(true, Ordering::Release);
                return Err(deadline_status());
            }
            if let Some(principal) = outcome.principal {
                parts.peer_id = principal;
            }
            for (k, v) in outcome.attributes {
                // The credential sets an enrolled peer's maximum roles.
                if credentialed && k == super::auth::ROLE_ATTRIBUTE {
                    continue;
                }
                attrs.entry(k).or_insert(v);
            }
        }
        gate3(&*routed.meta, &routed.header, &attrs)?;
        if let Target::HttpSession { factory, sid } = &routed.target {
            let instance = self
                .sessions
                .resolve_http(&parts.peer_id, &routed.key, sid, factory)
                .map_err(|error| error.status())?;
            routed.target = target_of(instance, &routed.foreign);
        }
        routed.attributes = attrs;
        Ok(Some(routed))
    }

    /// Hand a routed foreign call to the binding (synchronous; see
    /// `Foreign::deliver`).
    fn deliver_foreign(&self, mut routed: Routed, parts: CallParts, mut obs: CallObs) {
        // From the serve loop's fast path the call is not open yet.
        open_routed(&mut obs, &mut routed, &parts.peer_id);
        obs.dispatching(&routed.header, &parts.peer_id, &routed.attributes);
        let Routed {
            header,
            method_idx,
            target,
            attributes,
            deadline,
            call_admission,
            ..
        } = routed;
        let (svc, session) = match target {
            Target::Foreign { svc, session } => (svc, session),
            _ => unreachable!("deliver_foreign on a native target"),
        };
        self.foreign.deliver(
            super::foreign::Delivery {
                svc,
                method_idx,
                session,
                header,
                attributes,
                deadline,
                parts,
                obs,
                call_admission: call_admission.expect("foreign route admission"),
            },
            &self.deadlines,
        );
    }

    /// The Gate-3 [`AttributeStore`] this dispatcher checks. A transport's auth
    /// stage writes resolved caller attributes here (keyed by the call's peer
    /// id) before dispatching, so the capability gate sees them.
    pub fn attributes(&self) -> &AttributeStore {
        &self.attributes
    }

    /// Drop the HTTP-scoped session instances named `session_id` (the
    /// `aster-session-id` string), for every principal. Subsequent calls with
    /// that id create fresh instances. Connection-scoped (Iroh) sessions are
    /// not affected; they end with their connection
    /// ([`close_connection`](Dispatcher::close_connection)).
    pub fn end_session(&self, session_id: &str) {
        self.sessions.end_http_session(session_id);
    }

    /// Reap every session opened on `connection_id`, along with that
    /// connection's graveyard and session count (§7.5). [`Server::serve`] does
    /// this on the reactor's `ConnectionClosed`; a transport that assigns its
    /// own connection ids (see [`CallParts::with_connection_id`]) calls it when
    /// a connection ends. Returns the number of sessions dropped.
    pub fn close_connection(&self, connection_id: u64) -> usize {
        self.sessions.close_connection(connection_id)
    }
}

/// A pluggable additional transport for [`AsterServer`] — e.g. the HTTP/Salvo
/// transport. Defined here (in `aster`) so `aster` needn't depend on the
/// transport crate; the transport crate implements it for its config type and
/// `AsterServer::builder().with_http(cfg)` spawns it on the shared
/// [`Dispatcher`]. Off by default — Iroh-only unless one is attached.
pub trait HttpTransport: Send + 'static {
    /// Spawn the transport serving `dispatcher`; the returned handle is held by
    /// the [`AsterServer`] and aborted on shutdown.
    fn serve(self: Box<Self>, dispatcher: Dispatcher) -> tokio::task::JoinHandle<()>;
}

/// The connection-agnostic inputs the dispatcher needs for one call. The Iroh
/// reactor path builds this from an [`IncomingCall`] via
/// [`from_incoming`](CallParts::from_incoming); other transports (HTTP)
/// construct it directly — no `CoreConnection` required, because the dispatch
/// path never touches the connection (only the FFI bindings do).
///
/// A transport wires the two channels: it sends request frames into
/// `request_receiver` (the first inline as `request_payload` / `request_flags`)
/// and drains `response_sender` to write the response. For a unary call:
/// `request_payload` is the lone request frame, `request_flags` has
/// `FLAG_END_STREAM`, and `request_receiver` is an already-closed channel.
/// How the transport learned the peer identity on a call.
///
/// This is the difference between "the peer proved possession of the key" and
/// "something told us this string". A `peer_id` from an iroh QUIC connection is
/// the remote's authenticated node id; a `peer_id` from an HTTP or WebTransport
/// front end is whatever that front end decided to put there, which may be a
/// header a client supplied.
///
/// Coordination cares because a voter's identity IS its authority: a service
/// that admits the same apparent NodeId over an unauthenticated transport would
/// let anyone impersonate a voter. Hence [`ServiceDispatch::iroh_only`].
///
/// Deliberately not `Default`: a transport must state what it knows. The whole
/// point is that "unspecified" cannot silently become "authenticated".
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum PeerProvenance {
    /// The peer id is an iroh QUIC remote node id, authenticated by the
    /// transport's handshake.
    IrohAuthenticated,
    /// Any other transport. The peer id may be unauthenticated or supplied by
    /// the client; treat it as a hint, never as an authority.
    Other,
}

impl PeerProvenance {
    /// Whether this provenance carries transport-level proof of the identity.
    pub fn is_authenticated(self) -> bool {
        matches!(self, PeerProvenance::IrohAuthenticated)
    }
}

/// The dispatch-relevant parts of one call.
///
/// `#[non_exhaustive]` so a future transport cannot construct this with a
/// struct literal and get a defaulted `provenance`. New transports must go
/// through [`CallParts::new`] and say what they know about the peer — the
/// forgeable-by-omission failure this type exists to prevent.
#[non_exhaustive]
pub struct CallParts {
    pub peer_id: String,
    pub provenance: PeerProvenance,
    pub header_payload: Vec<u8>,
    pub request_payload: Vec<u8>,
    pub request_flags: u8,
    pub response_sender: ResponseSender,
    pub request_receiver: Receiver<RequestFrame>,
    pub cancelled: Arc<AtomicBool>,
    /// The connection the call arrived on, when the transport has one. Session
    /// scoping depends on it: `Some` gives connection-scoped sessions (§7.5),
    /// `None` gives HTTP-style principal-scoped sessions. Set by
    /// [`from_incoming`](CallParts::from_incoming), or
    /// [`with_connection_id`](CallParts::with_connection_id).
    pub connection_id: Option<u64>,
    /// The connection itself, when the transport has one. Only foreign
    /// (binding) calls use it, to give handlers tunnels and addresses.
    pub connection: Option<CoreConnection>,
    /// Fired when `cancelled` is set, so a waiter need not poll it (and a
    /// foreign call can hook it without a task). `None` for transports that
    /// only set the flag.
    pub cancel_notify: Option<Arc<CancelSignal>>,
}

impl CallParts {
    /// Construct from a transport that is not the iroh reactor. `provenance` is
    /// required rather than defaulted.
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        peer_id: String,
        provenance: PeerProvenance,
        header_payload: Vec<u8>,
        request_payload: Vec<u8>,
        request_flags: u8,
        response_sender: ResponseSender,
        request_receiver: Receiver<RequestFrame>,
        cancelled: Arc<AtomicBool>,
    ) -> Self {
        Self {
            peer_id,
            provenance,
            header_payload,
            request_payload,
            request_flags,
            response_sender,
            request_receiver,
            cancelled,
            connection_id: None,
            connection: None,
            cancel_notify: None,
        }
    }

    /// Mark the call as arriving on connection `connection_id`, so
    /// session-scoped services key their instances by `(connection, session
    /// id)` (§7.5). The transport must then call
    /// [`Dispatcher::close_connection`] when that connection ends, or its
    /// sessions are never reaped. Ids must be unique among live connections.
    pub fn with_connection_id(mut self, connection_id: u64) -> Self {
        self.connection_id = Some(connection_id);
        self
    }

    /// Extract the dispatch-relevant parts from a reactor [`IncomingCall`],
    /// dropping the ids the dispatcher doesn't use.
    ///
    /// This is the one path that may claim [`PeerProvenance::IrohAuthenticated`],
    /// because it is the one path whose peer id came from a completed iroh
    /// handshake.
    pub fn from_incoming(call: IncomingCall) -> Self {
        Self {
            peer_id: call.peer_id,
            provenance: PeerProvenance::IrohAuthenticated,
            header_payload: call.header_payload,
            request_payload: call.request_payload,
            request_flags: call.request_flags,
            response_sender: call.response_sender,
            request_receiver: call.request_receiver,
            cancelled: call.cancelled,
            connection_id: Some(call.connection_id),
            connection: Some(call.connection),
            cancel_notify: Some(call.cancel_notify),
        }
    }
}

/// Handle to a running [`Server`] loop: the RPC dispatch task plus the non-RPC
/// ALPN fan-out task (see [`Server::route_alpn`]).
pub struct ServerHandle {
    rpc_join: tokio::task::JoinHandle<()>,
    route_join: tokio::task::JoinHandle<()>,
}

impl ServerHandle {
    /// Stop both the RPC dispatch and ALPN fan-out loops.
    pub fn abort(&self) {
        self.rpc_join.abort();
        self.route_join.abort();
    }

    /// Await the loops. Resolves when they end (the node closed, or
    /// [`abort`](ServerHandle::abort) was called).
    pub async fn joined(self) {
        let _ = self.rpc_join.await;
        self.route_join.abort();
        let _ = self.route_join.await;
    }
}

/// The outcome of [`Dispatcher::route`].
pub enum Route {
    /// Every gate passed: run the handler ([`Dispatcher::complete`]).
    Dispatch(Routed),
    /// The synchronous gates passed, but the configured [`Authenticator`]
    /// must run before Gate 3; [`Dispatcher::complete`] does both.
    Authenticate(Routed),
    /// Refused before any handler: send this status as a trailer-only
    /// response.
    Reject(RpcStatus),
}

impl Route {
    /// The refusal status, if the call was rejected.
    pub fn rejection(&self) -> Option<&RpcStatus> {
        match self {
            Route::Reject(s) => Some(s),
            _ => None,
        }
    }
}

/// A call that passed routing: its decoded header and resolved target.
/// Opaque; hand it back to [`Dispatcher::complete`].
pub struct Routed {
    header: StreamHeader,
    key: ServiceKey,
    /// The registered instance (SHARED) or metadata probe (SESSION) the gates
    /// consult.
    meta: Arc<dyn ServiceDispatch>,
    /// Set for a foreign service (then `meta` is the same object).
    foreign: Option<Arc<ForeignService>>,
    /// The foreign method's index; `0` for native services.
    method_idx: u32,
    target: Target,
    attributes: HashMap<String, String>,
    deadline: Option<Instant>,
    call_admission: Option<DispatchPermit>,
}

impl Routed {
    /// The decoded request header.
    pub fn header(&self) -> &StreamHeader {
        &self.header
    }

    /// When the handler will be cancelled with `DEADLINE_EXCEEDED`, if ever.
    pub fn deadline(&self) -> Option<Instant> {
        self.deadline
    }

    /// Whether the call goes to a foreign (binding-implemented) service.
    pub fn is_foreign(&self) -> bool {
        self.foreign.is_some()
    }
}

enum Target {
    /// The instance that will handle the call.
    Ready(Arc<dyn ServiceDispatch>),
    /// A foreign service, and its session for a session-scoped one.
    Foreign {
        svc: Arc<ForeignService>,
        session: Option<Arc<ForeignSession>>,
    },
    /// An HTTP-scoped session whose instance depends on the principal the
    /// authenticator resolves.
    HttpSession {
        factory: SessionFactory,
        sid: String,
    },
}

/// The target for a resolved session instance.
fn target_of(inst: SessionInstance, foreign: &Option<Arc<ForeignService>>) -> Target {
    match (inst, foreign) {
        (SessionInstance::Native(inst), _) => Target::Ready(inst),
        (SessionInstance::Foreign(session), Some(svc)) => Target::Foreign {
            svc: svc.clone(),
            session: Some(session),
        },
        (SessionInstance::Foreign(_), None) => {
            unreachable!("foreign session for a native service")
        }
    }
}

fn not_found(header: &StreamHeader) -> RpcStatus {
    RpcStatus::error(
        StatusCode::NotFound,
        format!("service '{}' v{} not found", header.service, header.version),
    )
}

/// Gate 3: the service-level requirement, then the method-level one; both must
/// pass against the caller's resolved attributes.
fn gate3(
    meta: &dyn ServiceDispatch,
    header: &StreamHeader,
    attrs: &HashMap<String, String>,
) -> std::result::Result<(), RpcStatus> {
    for req in [
        meta.service_requires(),
        meta.method_requires(&header.method),
    ]
    .into_iter()
    .flatten()
    {
        if !evaluate_capability(&req, attrs) {
            return Err(RpcStatus::error(
                StatusCode::PermissionDenied,
                format!(
                    "capability check failed for '{}.{}'",
                    header.service, header.method
                ),
            ));
        }
    }
    Ok(())
}

/// Open a routed call's telemetry (no-op if already open): its `rpc` span and
/// started count, with the method's pattern when routing knows it.
fn open_routed(obs: &mut CallObs, routed: &mut Routed, peer: &str) {
    #[cfg(feature = "otel")]
    let pattern = routed
        .foreign
        .as_ref()
        .and_then(|svc| svc.def.method(routed.method_idx))
        .map(|m| super::observe::otel::pattern_name(m.pattern));
    #[cfg(not(feature = "otel"))]
    let pattern = None;
    obs.open(&mut routed.header, peer, pattern);
}

/// Finish the telemetry of a call refused before any handler ran. The header
/// is decoded again only when the refusal is actually logged or recorded.
pub(crate) fn finish_refused(mut obs: CallObs, parts: &CallParts, status: &RpcStatus) {
    let code = status.status_code();
    if !tracing::enabled!(target: DISPATCH, Level::DEBUG) && !obs.wants_header() {
        obs.finish(code, CallInfo::default());
        return;
    }
    let mut header = decode_stream_header(&parts.header_payload).ok();
    match header.as_mut() {
        // Routing found the service and method (the refusal came later: Gate
        // 3, a session rule, the authenticator): label them. An unknown
        // service or method is the caller's choice and must not mint series.
        Some(h) if !matches!(code, StatusCode::NotFound | StatusCode::Unimplemented) => {
            obs.open(h, &parts.peer_id, None)
        }
        Some(h) => obs.open_unrouted(h, &parts.peer_id),
        None => obs.open_unrouted(&mut StreamHeader::default(), &parts.peer_id),
    }
    let (service, method, call_id) = header.as_ref().map_or(("", "", 0), |h| {
        (h.service.as_str(), h.method.as_str(), h.call_id)
    });
    obs.span().in_scope(|| {
        tracing::debug!(
            target: DISPATCH,
            service,
            method,
            call_id,
            peer = parts.peer_id.as_str(),
            status = ?code,
            message = status.message.as_str(),
            "rpc refused"
        )
    });
    obs.finish(
        code,
        CallInfo {
            service,
            method,
            call_id,
            peer: &parts.peer_id,
        },
    );
}

/// The status a call fails with when one of its request frames does not
/// inflate: the caller sent bytes that are not a valid frame payload, so it
/// is the caller's error, exactly as for a first frame (§5.6).
pub(crate) fn corrupt_frame_status(err: &impl std::fmt::Display) -> RpcStatus {
    RpcStatus::error(
        StatusCode::InvalidArgument,
        format!("request payload: {err}"),
    )
}

/// Log a corrupt request frame. `frame` is its position in the request
/// stream (0 = the first frame, delivered with the header).
pub(crate) fn warn_corrupt_frame(
    header: &StreamHeader,
    peer: &str,
    frame: u64,
    err: &dyn std::fmt::Display,
) {
    warn_corrupt(
        &header.service,
        &header.method,
        header.call_id,
        peer,
        frame,
        err,
    );
}

fn warn_corrupt(
    service: &str,
    method: &str,
    call_id: i32,
    peer: &str,
    frame: u64,
    err: &dyn std::fmt::Display,
) {
    tracing::warn!(
        target: DISPATCH,
        service,
        method,
        call_id,
        peer,
        frame,
        error = %err,
        "corrupt request frame; failing the call with INVALID_ARGUMENT"
    );
}

/// Send a refusal trailer without spawning when the response queue has room
/// (it always does for a fresh call); fall back to a task only if it is full.
pub(crate) fn reject_now(sender: ResponseSender, status: &RpcStatus) {
    let Ok(bytes) = encode_rpc_status(status) else {
        return;
    };
    let Ok(frame) = encode_frame(&bytes, FLAG_TRAILER) else {
        return;
    };
    let frame = OutgoingFrame::Trailer(frame);
    match sender.try_reserve(frame.encoded_len()) {
        Ok(permit) => {
            let _ = permit.send(frame);
        }
        Err(ResponseReserveError::Full) => {
            tokio::spawn(async move {
                let _ = sender.send(frame).await;
            });
        }
        Err(_) => {}
    }
}

/// Resolves when the transport cancels the call (flag set, signal fired);
/// never for a transport without a signal.
async fn peer_cancelled(signal: Option<Arc<CancelSignal>>, cancelled: Arc<AtomicBool>) {
    let Some(signal) = signal else {
        return std::future::pending().await;
    };
    let notified = signal.notified();
    tokio::pin!(notified);
    notified.as_mut().enable();
    if cancelled.load(Ordering::Acquire) {
        return;
    }
    notified.await;
}

/// Send a trailer-only error response (no data frame) before a [`Call`] exists.
/// Async because the response channel is bounded (§12.4). Every caller is
/// already in an async context; the alternative would be dropping a trailer
/// when the channel is momentarily full, which leaves the peer waiting for a
/// terminator that never comes.
async fn emit_trailer(sender: &ResponseSender, code: StatusCode, message: &str) {
    emit_rpc_status(sender, &RpcStatus::error(code, message)).await;
}

/// Send an already-built [`RpcStatus`] as a trailer-only response. Used by the
/// auth hook to surface its own status (code + message + details).
async fn emit_rpc_status(sender: &ResponseSender, status: &RpcStatus) {
    if let Ok(bytes) = encode_rpc_status(status) {
        if let Ok(frame) = encode_frame(&bytes, FLAG_TRAILER) {
            let _ = sender.send(OutgoingFrame::Trailer(frame)).await;
        }
    }
}

/// Build a metadata map from a header's parallel key/value vectors.
fn metadata_map(h: &StreamHeader) -> HashMap<String, String> {
    h.metadata_keys
        .iter()
        .cloned()
        .zip(h.metadata_values.iter().cloned())
        .collect()
}

/// The session id of an HTTP-style call (no connection id): the
/// `aster-session-id` metadata header, else a non-zero `StreamHeader.session_id`.
fn http_session_id(h: &StreamHeader) -> Option<String> {
    for (k, v) in h.metadata_keys.iter().zip(h.metadata_values.iter()) {
        if k == "aster-session-id" && !v.is_empty() {
            return Some(v.clone());
        }
    }
    (h.session_id != 0).then(|| h.session_id.to_string())
}

/// Per-call server context: request input, response output, and the decoded
/// [`StreamHeader`]. Pull requests with [`recv_request`](Call::recv_request),
/// emit streaming items with [`send`](Call::send), and terminate with
/// [`respond`](Call::respond) (unary) or [`finish`](Call::finish) (streaming).
pub struct Call {
    header: StreamHeader,
    attributes: HashMap<String, String>,
    peer_id: String,
    provenance: PeerProvenance,
    cancelled: Arc<AtomicBool>,
    response_sender: ResponseSender,
    /// The first request payload, delivered inline by the reactor (taken once).
    first_request: Option<Vec<u8>>,
    /// Additional request frames (client-stream / bidi). `None` once taken by
    /// [`take_requests`](Call::take_requests).
    request_receiver: Option<Receiver<RequestFrame>>,
    /// Whether the first request frame carried `FLAG_END_STREAM` (a single-frame
    /// request stream). The reactor only opens the per-call request channel when
    /// there are *additional* frames to forward; if the first frame already ended
    /// the stream, the channel is never closed, so we must not block reading it.
    first_is_end: bool,
    deadline: Option<Instant>,
    /// Request frames read after the first (for the corrupt-frame log).
    frames_read: u64,
    /// The terminal status this call sent, or that the server sent for it (a
    /// corrupt request frame); first one wins.
    sent: Option<StatusCode>,
    obs: CallObs,
}

impl Drop for Call {
    fn drop(&mut self) {
        let code = match self.sent {
            Some(code) => code,
            None if self.deadline.is_some_and(|at| Instant::now() >= at) => {
                StatusCode::DeadlineExceeded
            }
            None if self.is_cancelled() => StatusCode::Cancelled,
            // Dropped without a trailer: the peer sees the stream end.
            None => StatusCode::Internal,
        };
        self.obs.finish(
            code,
            CallInfo {
                service: &self.header.service,
                method: &self.header.method,
                call_id: self.header.call_id,
                peer: &self.peer_id,
            },
        );
    }
}

impl Call {
    fn new(
        inner: CallParts,
        header: StreamHeader,
        attributes: HashMap<String, String>,
        deadline: Option<Instant>,
        obs: CallObs,
    ) -> Self {
        let CallParts {
            peer_id,
            provenance,
            cancelled,
            response_sender,
            request_payload,
            request_receiver,
            request_flags,
            ..
        } = inner;
        let first_is_end = request_flags & FLAG_END_STREAM != 0;
        Self {
            header,
            attributes,
            peer_id,
            provenance,
            cancelled,
            response_sender,
            first_request: Some(request_payload),
            request_receiver: Some(request_receiver),
            first_is_end,
            deadline,
            frames_read: 0,
            sent: None,
            obs,
        }
    }

    /// When the server will cancel this call with `DEADLINE_EXCEEDED`: the
    /// minimum of the caller's header deadline, the method's
    /// [`method_timeout`](ServiceDispatch::method_timeout) and the server's
    /// [`handler_timeout`](Server::handler_timeout). `None` = no deadline.
    pub fn deadline(&self) -> Option<Instant> {
        self.deadline
    }

    /// The decoded request header.
    pub fn header(&self) -> &StreamHeader {
        &self.header
    }

    /// The method being invoked.
    pub fn method(&self) -> &str {
        &self.header.method
    }

    /// The remote peer's id (hex).
    pub fn peer(&self) -> &str {
        &self.peer_id
    }

    /// How the transport learned [`peer`](Call::peer).
    ///
    /// A handler that treats the peer id as an authorization input should check
    /// this, or declare its service
    /// [`iroh_only`](ServiceDispatch::iroh_only) and let dispatch reject the
    /// call before the handler runs.
    pub fn provenance(&self) -> PeerProvenance {
        self.provenance
    }

    /// The peer's authorization attributes (from the server's
    /// [`AttributeStore`](super::auth::AttributeStore)) — e.g. `aster.role`.
    /// Already consulted for the Gate-3 check; exposed for handler-level
    /// decisions. Empty if the peer has no recorded attributes.
    pub fn attributes(&self) -> &HashMap<String, String> {
        &self.attributes
    }

    /// Whether the peer has cancelled the call (or the stream errored). Poll
    /// this from long-running streaming handlers to stop early.
    pub fn is_cancelled(&self) -> bool {
        self.cancelled.load(Ordering::Acquire)
    }

    /// Receive the next request payload. Returns the first request (delivered
    /// inline by the reactor) on the first call, then subsequent client-stream /
    /// bidi frames, then `None` once the request stream ends.
    pub async fn recv_request(&mut self) -> Option<Vec<u8>> {
        if let Some(first) = self.first_request.take() {
            return Some(first);
        }
        // Single-frame request stream: the reactor never closes the request
        // channel in this case, so reading it would block forever.
        if self.first_is_end {
            return None;
        }
        let rx = self.request_receiver.as_mut()?;
        match next_request_frame(rx).await {
            NextFrame::Frame(p) => {
                self.frames_read += 1;
                Some(p)
            }
            NextFrame::End => None,
            // The caller sent a frame that is not a valid payload. Fail the
            // call here, as for a corrupt first frame, rather than let the
            // handler mistake it for the end of the stream and answer OK:
            // the trailer goes out first, so anything the handler sends after
            // finds the stream finished.
            NextFrame::Corrupt(err) => {
                self.frames_read += 1;
                warn_corrupt_frame(&self.header, &self.peer_id, self.frames_read, &err);
                let status = corrupt_frame_status(&err);
                self.sent.get_or_insert(StatusCode::InvalidArgument);
                self.cancelled.store(true, Ordering::Release);
                emit_rpc_status(&self.response_sender, &status).await;
                None
            }
        }
    }

    /// Emit one streaming response data frame.
    ///
    /// Async since §12.4 bounded the response channel: awaiting here is the
    /// backpressure. A handler producing faster than the peer reads is slowed
    /// down rather than queueing without limit — which is the whole point, as
    /// the peer controls that memory.
    pub async fn send(&self, payload: Vec<u8>) -> Result<()> {
        let frame = encode_payload_frame(&payload, 0)?;
        self.response_sender
            .send(OutgoingFrame::Frame(frame))
            .await
            .map_err(|_| channel_closed())
    }

    /// Complete a unary (or client-stream) call: one response payload plus the
    /// terminal trailer, in a single write. An empty `payload` sends the trailer
    /// only (a data frame can't carry an empty payload) — the client observes an
    /// empty response with the given status.
    pub async fn respond(mut self, payload: Vec<u8>, status: &RpcStatus) -> Result<()> {
        self.sent.get_or_insert(status.status_code());
        let trailer = encode_frame(&encode_rpc_status(status)?, FLAG_TRAILER)?;
        let buf = if payload.is_empty() {
            trailer
        } else {
            let mut b = encode_payload_frame(&payload, 0)?;
            b.extend_from_slice(&trailer);
            b
        };
        self.response_sender
            .send(OutgoingFrame::CompleteUnary(buf))
            .await
            .map_err(|_| channel_closed())
    }

    /// Finish a streaming call with the terminal trailer (status). Use after the
    /// last [`send`](Call::send), or on its own to fail a call before any data.
    pub async fn finish(mut self, status: &RpcStatus) -> Result<()> {
        self.sent.get_or_insert(status.status_code());
        let frame = encode_frame(&encode_rpc_status(status)?, FLAG_TRAILER)?;
        self.response_sender
            .send(OutgoingFrame::Trailer(frame))
            .await
            .map_err(|_| channel_closed())
    }

    /// A typed output sink sharing this call's response channel (server-stream /
    /// bidi). The call retains the trailer side — `finish` after the handler
    /// returns. Used by `#[aster::service]`-generated dispatchers.
    pub fn response_sink<T>(&self, fory: Arc<Fory>) -> ResponseSink<T> {
        ResponseSink::new(self.response_sender.clone(), fory)
    }

    /// Take the inbound request side as a typed [`RequestStream`] (client-stream /
    /// bidi), leaving the response side intact. Used by generated dispatchers.
    pub fn take_requests<T>(&mut self, fory: Arc<Fory>) -> RequestStream<T> {
        let failer = CallFailer {
            sender: self.response_sender.clone(),
            cancelled: self.cancelled.clone(),
            service: self.header.service.clone(),
            method: self.header.method.clone(),
            call_id: self.header.call_id,
            peer: self.peer_id.clone(),
        };
        RequestStream::new(
            self.first_request.take(),
            self.request_receiver.take(),
            self.first_is_end,
            fory,
            failer,
        )
    }
}

/// One read from a call's request stream after the first frame.
pub(crate) enum NextFrame {
    /// The next request payload, inflated.
    Frame(Vec<u8>),
    /// The request stream ended (or the transport broke).
    End,
    /// The frame did not inflate (corrupt, or over the 16 MiB bomb limit).
    /// The channel is closed; no further frames are accepted. The caller
    /// fails the call with [`corrupt_frame_status`].
    Corrupt(String),
}

/// Read the next client-stream / bidi request frame, inflating it if it is
/// `FLAG_COMPRESSED`.
pub(crate) async fn next_request_frame(rx: &mut Receiver<RequestFrame>) -> NextFrame {
    let Some(f) = rx.recv().await else {
        return NextFrame::End;
    };
    match payload_of(f.payload, f.flags) {
        Ok(p) => NextFrame::Frame(p),
        Err(e) => {
            rx.close();
            NextFrame::Corrupt(e.to_string())
        }
    }
}

/// Everything a detached request reader ([`RequestStream`]) needs to fail
/// its call when a request frame is corrupt: the server sends the
/// `INVALID_ARGUMENT` trailer itself, so the caller sees the failure whatever
/// the handler then does with the error.
pub(crate) struct CallFailer {
    sender: ResponseSender,
    cancelled: Arc<AtomicBool>,
    service: String,
    method: String,
    call_id: i32,
    peer: String,
}

impl CallFailer {
    /// Log, flag the call over, and send `status` as its trailer. Later
    /// response writes find the stream finished.
    pub(crate) async fn fail(&self, frame: u64, err: &str, status: &RpcStatus) {
        warn_corrupt(
            &self.service,
            &self.method,
            self.call_id,
            &self.peer,
            frame,
            &err,
        );
        self.cancelled.store(true, Ordering::Release);
        emit_rpc_status(&self.sender, status).await;
    }
}

fn channel_closed() -> Error {
    Error::Connection("rpc response channel closed (call cancelled or connection gone)".into())
}
